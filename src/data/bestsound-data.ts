/**
 * BestSound demo ledger, imported from "Contabilidade - BestSound v2.xlsx".
 *
 * LEDGER rows: [date, amount (+ income / − expense), category, note]
 * LOTS: per-lot sales [date, price, note] and costs [label, −value]
 */
export type LedgerRow = [date: string, amount: number, category: string, note: string];
export type LotSaleRow = [date: string, price: number, note: string];
export type LotCostRow = [label: string, value: number];
export interface LotSource {
  product: 'Alarmes' | 'GPS' | 'Rádios';
  lot: string;
  sales: LotSaleRow[];
  costs: LotCostRow[];
}

/** Expand `n` identical sale rows on one date. */
const rep = (date: string, price: number, n: number, note = ''): LotSaleRow[] =>
  Array.from({ length: n }, () => [date, price, note] as LotSaleRow);

